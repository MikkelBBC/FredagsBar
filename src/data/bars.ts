import type { Bar, Opening } from './types';

export const SEMESTER_START = '2026-08-31';
export const SEMESTER_END = '2026-12-18';

/** Alle dage med en given ugedag i semesteret med samme åbningstid. */
function weekly(dow: number, open: string, close: string, overrides: Record<string, [string, string]> = {}, skip: string[] = []): Opening[] {
  const out: Opening[] = [];
  const [sy, sm, sd] = SEMESTER_START.split('-').map(Number);
  const [ey, em, ed] = SEMESTER_END.split('-').map(Number);
  const d = new Date(sy, sm - 1, sd, 12);
  const end = new Date(ey, em - 1, ed, 12);
  while (d <= end) {
    if (d.getDay() === dow) {
      const date = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
      if (!skip.includes(date)) {
        const ov = overrides[date];
        out.push({ date, open: ov ? ov[0] : open, close: ov ? ov[1] : close });
      }
    }
    d.setDate(d.getDate() + 1);
  }
  return out;
}

const fridays = (open: string, close: string, overrides?: Record<string, [string, string]>, skip?: string[]) =>
  weekly(5, open, close, overrides, skip);

const dates = (list: string[], open: string, close: string): Opening[] =>
  list.map((date) => ({ date: date.length === 5 ? `2026-${date}` : date, open, close }));

